// multi Dimensional array
public class ArrayExample3 {
    public static void main(String [] args){
        double[][] matrix = {
                {1,2,3},
                {3,4,55,6},
                {3,7,8,9},
                {5,8,0,2,1}
        };
        System.out.println(matrix[0][2]);
        System.out.println(matrix[3][4]);

    }
}
