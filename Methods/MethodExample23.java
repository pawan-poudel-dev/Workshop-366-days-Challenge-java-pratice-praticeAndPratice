public class MethodExample23 {
    static void myMethod(String fname, int age){
        System.out.println(fname + " "+ age);
    }
    public static void main(String [] args){
        myMethod("Pawan",5);
        myMethod("Jenny", 8);
        myMethod("Anja",32);
    }
}
// pawan 5 
// jenny 8
// anja is 31