/*
Declare one variable of each of the 8 primitive types with a sensible value, and print all of them with labels.

 */

package TernaryCondition;

public class PrimitiveDataTypes {
    public static void main(String [] args){
        byte age = 25;
        short year = 2026;
        int population = 1000000;
        long distance = 9876543210L;
        float height = 5.9f;
        double price = 1999.99;
        char grade = 'A';
        boolean isStudent = true;

        System.out.println("Byte value: " + age);
        System.out.println("Short value: " + year);
        System.out.println("Int value: " + population);
        System.out.println("Long value: " + distance);
        System.out.println("Float value: " + height);
        System.out.println("Double value: " + price);
        System.out.println("Char value: " + grade);
        System.out.println("Boolean value: " + isStudent);

    }
}
