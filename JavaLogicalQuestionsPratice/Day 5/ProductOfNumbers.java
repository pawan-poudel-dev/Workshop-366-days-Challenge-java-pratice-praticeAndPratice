public class ProductOfNumbers {
    public static void main(String [] args){
        // finding  out the product of the number
        // or we can simply say that finding out the facctorial of number
        int i;
        int n = 5;
        int product = 1;
        for(i = 1;i<= n; i++){
            product = product *i;

        }
        System.out.println(product);
    }
}
