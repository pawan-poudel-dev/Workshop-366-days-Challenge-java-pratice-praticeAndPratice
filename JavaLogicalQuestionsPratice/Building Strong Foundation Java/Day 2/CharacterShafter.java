/*

Character Shifter
Declare char ch = 'A'. Add 3 to it and print the resulting character.
Then declare char lower = 'z'. Subtract 2 and print the result.
(Hint: type casting)


*/
public class CharacterShafter {
    public static void main(String[] args) {
        char ch = 'A' + 3;
        char lower = 'z' - 2;
        System.out.println(((int) ch));
        System.out.println(((int) lower));

    }

}
