/*
Rupees to Paisa
You have rupees = 150. Convert and print the total paisa. (1 rupee = 100 paisa)



*/
public class CoinConverter {
    public static void main(String[] args) {
        double rupees = 150;
        // 1 rupees = 100vpaisa
        int  paisa = rupees * 100;
        System.out.println("Total paisa :" + paisa);
    }

}
