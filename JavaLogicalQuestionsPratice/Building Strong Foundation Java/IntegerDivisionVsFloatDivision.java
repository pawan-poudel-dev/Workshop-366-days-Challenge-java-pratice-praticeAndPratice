/*
Integer Division vs Float Division
Divide 7 by 2 using integer division and then using double division. Print both results and observe the difference.



*/
public class IntegerDivisionVsFloatDivision {
    public static void main(String[] args) {
        int a = 7;
        int b = 2;
        System.out.println("Integer Division : " + (a / b));
        System.out.println("Float Division :  " + ((double)a/b));

    }

}
