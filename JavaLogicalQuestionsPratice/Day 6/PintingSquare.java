class PintingSquare{
    public static void main(String [] args){
        //  printing the square of stars 5  *5
        // using for nested loop
        int i,j;
        for(int i = 5; i>=1;i--){
            for(j = 5; j>= i;j++){
                System.out.println("*");
            }
        }
    }
}